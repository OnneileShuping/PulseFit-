    /**
     * Returns `count` DISTINCT tips for the given activity type (case-insensitive, fallback to General).
     */
    fun randomTips(
        type: String,
        count: Int = 3,
        random: Random = Random.Default
    ): List<String> {
        val tips = library.entries
            .find { it.key.equals(type, ignoreCase = true) }
            ?.value ?: library["General"] ?: emptyList()

        if (tips.isEmpty()) return emptyList()

        return tips.shuffled(random).take(minOf(count, tips.size))
    }

    /**
     * Deterministically returns a single tip of the day based on day index.
     */
    fun tipOfTheDay(
        type: String,
        nowMillis: Long = System.currentTimeMillis(),
        tz: TimeZone = TimeZone.getDefault()
    ): String {
        val tips = library.entries
            .find { it.key.equals(type, ignoreCase = true) }
            ?.value ?: library["General"] ?: emptyList()

        if (tips.isEmpty()) return "Stay active and listen to your body today!"

        val dayIndex = DayUtil.dayIndex(nowMillis, tz)
        val index = Math.floorMod(dayIndex, tips.size.toLong()).toInt()
        return tips[index]
    }
